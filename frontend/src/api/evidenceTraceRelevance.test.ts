import { describe, expect, it } from "vitest";
import { adaptEvidenceTraceItemResponse, adaptRelevanceJudgment } from "./evidenceTrace";
import judged from "./__fixtures__/evidence_trace_relevance_judged.json";
import unresolved from "./__fixtures__/evidence_trace_relevance_unresolved.json";
import failed from "./__fixtures__/evidence_trace_relevance_failed.json";
import unjudged from "./__fixtures__/evidence_trace_relevance_unjudged.json";
import judgedV2 from "./__fixtures__/evidence_trace_relevance_judged_v2.json";
import judgedV3 from "./__fixtures__/evidence_trace_relevance_judged_v3.json";
import legacyClaim from "./__fixtures__/evidence_trace_claim_31.json";

/**
 * P4 phase 1 -- the relevance judgment in the trace adapter. The four fixtures are REAL backend output (generated by
 * p4_phase1_20261012/tools/make_relevance_fixtures.py from the production trace route over a copy of the NVDA Fresh Run #2, judged by
 * the SIMULATED gateway -- test data), not hand-written. Expectations are read from each payload, never restated as constants.
 */

type Payload = { item: { relevance_judgment: Record<string, unknown> } };

function relevanceOf(payload: unknown) {
  const adapted = adaptEvidenceTraceItemResponse(payload);
  if (!adapted.ok) throw new Error(adapted.reason);
  return adapted.value.item.relevance_judgment;
}

const raw = (payload: unknown) => (payload as Payload).item.relevance_judgment;
const copyOf = (payload: unknown): Payload => JSON.parse(JSON.stringify(payload));

describe("trace adapter: relevance judgment", () => {
  it("copies a judged pair: tier, definition anchors, basis, test-data flag and every source identity", () => {
    const r = relevanceOf(judged);
    const source = raw(judged).source as Record<string, unknown>;
    const ledger = source.ledger as Record<string, unknown>;
    expect(r).toMatchObject({
      state: "JUDGED",
      tier: raw(judged).tier,
      basis: raw(judged).basis,
      test_data: true,
      model_weight: null,
      source: {
        execution_run_id: source.execution_run_id,
        based_on_run_id: source.based_on_run_id,
        owner_run_id: source.owner_run_id,
        call_id: source.call_id,
        provider: source.provider,
        ledger_integrity: ledger.integrity,
      },
    });
    expect(r?.tier).not.toBeNull();
    expect(r?.anchors.map((a) => a.element_id)).toEqual((raw(judged).anchors as { element_id: string }[]).map((a) => a.element_id));
    expect(r?.anchors[0]?.occurrences.length ?? 0).toBeGreaterThan(0);
  });

  it("keeps an unresolved, a failed and an unjudged pair without a tier, each with its own reason", () => {
    expect(relevanceOf(unresolved)).toMatchObject({ state: "UNRESOLVED", tier: null, unresolved_reason: raw(unresolved).unresolved_reason });
    expect(relevanceOf(failed)).toMatchObject({ state: "FAILED", tier: null, reason: raw(failed).reason });
    expect(relevanceOf(unjudged)).toMatchObject({ state: "UNJUDGED", tier: null, reason: raw(unjudged).reason, test_data: false });
  });

  it("never shows a tier for a state other than JUDGED, nor one outside the four-tier vocabulary", () => {
    const tampered = copyOf(failed);
    tampered.item.relevance_judgment.tier = "core";
    expect(relevanceOf(tampered)?.tier).toBeNull();
    const illegal = copyOf(judged);
    illegal.item.relevance_judgment.tier = "moderate";
    expect(relevanceOf(illegal)?.tier).toBeNull();
  });

  it("copies the quoted claim words of a prompt-v2 judgment and the versions its record was made under", () => {
    // P4 session 4 fixture: real backend output of the same chain, judged under prompt v2 / output v2 by the simulated gateway (TEST DATA)
    const r = relevanceOf(judgedV2);
    const rawAnchors = raw(judgedV2).anchors as { element_id: string; evidence_quotes: string[] }[];
    const source = raw(judgedV2).source as Record<string, unknown>;
    expect(r?.anchors.map((a) => a.evidence_quotes)).toEqual(rawAnchors.map((a) => a.evidence_quotes));
    expect(r?.anchors[0]?.evidence_quotes.length ?? 0).toBeGreaterThan(0);
    expect(r?.source.prompt_version).toBe(source.prompt_version);
    expect(r?.source.prompt_version).toContain("prompt.v2");
    // a prompt-v1 judgment keeps its own version label and has no quotes
    expect(relevanceOf(judged)?.source.prompt_version).toContain("prompt.v1");
    expect(relevanceOf(judged)?.anchors.every((a) => a.evidence_quotes.length === 0)).toBe(true);
  });

  it("drops quotes that are not strings or are blank", () => {
    const tampered = copyOf(judgedV2);
    const anchors = tampered.item.relevance_judgment.anchors as { evidence_quotes: unknown[] }[];
    anchors[0]!.evidence_quotes = ["kept words", 7, "  ", null];
    expect(relevanceOf(tampered)?.anchors[0]?.evidence_quotes).toEqual(["kept words"]);
  });

  it("copies the statement modes, the statements and the tier source of a prompt-v3 judgment", () => {
    // P4 session 6 fixture: real backend output of the same chain under prompt v3 / output v3, simulated gateway (TEST DATA)
    const r = relevanceOf(judgedV3);
    const rawJudgment = raw(judgedV3) as { tier_source: string; statements: { quote: string; mode: string; hit: boolean }[] };
    const rawAnchors = raw(judgedV3).anchors as { evidence_modes: string[] }[];
    expect(r?.anchors.map((a) => a.evidence_modes)).toEqual(rawAnchors.map((a) => a.evidence_modes));
    expect(r?.tier_source).toBe(rawJudgment.tier_source);
    expect(r?.statements.map((s) => [s.quote, s.mode, s.hit])).toEqual(rawJudgment.statements.map((s) => [s.quote, s.mode, s.hit]));
    expect(r?.source.prompt_version).toContain("prompt.v3");
    // older judgments carry no modes, statements or tier source
    expect(relevanceOf(judgedV2)?.statements).toEqual([]);
    expect(relevanceOf(judgedV2)?.tier_source).toBeNull();
    expect(relevanceOf(judged)?.anchors.every((a) => a.evidence_modes.length === 0)).toBe(true);
  });

  it("drops statements without a quote", () => {
    const tampered = copyOf(judgedV3);
    const judgment = tampered.item.relevance_judgment as { statements: unknown[] };
    judgment.statements = [{ quote: "", mode: "assertion", hit: true }, { quote: "kept words", hit: false }, 7];
    expect(relevanceOf(tampered)?.statements.map((s) => s.quote)).toEqual(["kept words"]);
  });

  it("is null for an unknown state, a missing contract, or a payload without the field", () => {
    expect(adaptRelevanceJudgment({ ...raw(judged), state: "MAYBE" })).toBeNull();
    expect(adaptRelevanceJudgment({ ...raw(judged), contract: null })).toBeNull();
    expect(relevanceOf(legacyClaim)).toBeNull();
  });
});
