import { describe, expect, it } from "vitest";
import { adaptEvidenceTraceItemResponse, adaptKeyConclusionsResponse } from "./evidenceTrace";
import admitted from "./__fixtures__/evidence_trace_consumption_admitted.json";
import excluded from "./__fixtures__/evidence_trace_consumption_excluded.json";
import negationGoverns from "./__fixtures__/evidence_trace_consumption_negation_governs.json";
import negationReread from "./__fixtures__/evidence_trace_consumption_negation_reread.json";
import negationUnanchored from "./__fixtures__/evidence_trace_consumption_negation_unanchored.json";
import unjudged from "./__fixtures__/evidence_trace_consumption_unjudged.json";
import legacyClaim from "./__fixtures__/evidence_trace_claim_31.json";

/**
 * alpha_evidence_consumption.v2 in the trace adapter. The three consumption fixtures are REAL backend output (generated by
 * tools/make_consumption_fixtures.py from the production trace route over the NVDA Fresh Run #2 saved inputs), not hand-written.
 * The adapter copies every field explicitly -- a field it silently dropped would never reach the UI however the type reads.
 */

function consumptionOf(payload: unknown) {
  const adapted = adaptEvidenceTraceItemResponse(payload);
  if (!adapted.ok) throw new Error(adapted.reason);
  return adapted.value.item.consumption;
}

describe("trace adapter: consumption block", () => {
  it("copies the execution basis and WHOSE ledger corroborated the stance (an original run: its own ledger)", () => {
    const c = consumptionOf(excluded);
    expect(c?.execution_basis).toMatchObject({
      execution_run_id: "12591384-0b26-470d-a99d-a49c00be440b",
      execution_type: null,
      based_on_run_id: null,
      recomputation_of_saved_inputs: false,
      label: "Original research run.",
      stance_ledger: { available: true, integrity: "MATCHES_MANIFEST", owner_run_id: "12591384-0b26-470d-a99d-a49c00be440b", binding: "OWN_RUN" },
    });
    expect(c?.execution_basis?.stance_ledger?.sha256).toMatch(/^[0-9a-f]{64}$/);
    expect(c?.binding).toMatchObject({ ledger_owner_run_id: "12591384-0b26-470d-a99d-a49c00be440b", ledger_binding: "OWN_RUN" });
  });

  it("copies the stance, the admission, the name decision, the weight and the binding of an admitted claim", () => {
    const c = consumptionOf(admitted);
    expect(c).not.toBeNull();
    expect(c).toMatchObject({
      contract: "alpha_evidence_consumption.v2",
      state: "CURRENT",
      verification_error: null,
      alpha_id: "A301",
      policies: { stance: "alpha_stance_policy.v1", attribution: "company_attribution.name.v1", relevance: "alpha_relevance_fallback.v1" },
      text_rule: { relation: "activation", assertion_status: "asserted", semantic_polarity: "activation" },
      stance: { state: "MODEL_JUDGED", label: "supports_alpha", method: "llm", version: "evidence_stance.llm.v1", ledger: "VERIFIED", unjudged_category: null },
      positive_admission: { admitted: true, reason_code: null, label: null, policy: "alpha_stance_policy.v1" },
      attribution: { category: "NO_TARGET_NAME", ticker_specific: false, subject_determined: false, limits: [], basis: [] },
      relevance: { state: "UNJUDGED", model_level: null, model_weight: null, lexical_baseline: 0.1873, effective_weight: 0.1873, weight_authority: "LEXICAL_RULE_FALLBACK" },
      binding: { ledger_integrity: "MATCHES_MANIFEST" },
    });
    expect(c?.binding?.input_sha256).toMatch(/^[0-9a-f]{64}$/);
    expect(c?.binding?.source_state_sha256).toMatch(/^[0-9a-f]{64}$/);
    expect(c?.stance?.explanation).toContain("confirmed by the run's own validated ledger output");
  });

  it("copies the shared reason code and the excluded label of a claim kept out of the positive pool", () => {
    const c = consumptionOf(excluded);
    expect(c?.stance).toMatchObject({ state: "MODEL_JUDGED", label: "opposes_alpha" });
    expect(c?.positive_admission).toMatchObject({ admitted: false, reason_code: "STANCE_MODEL_NOT_SUPPORTING", label: "opposes_alpha" });
    expect(c?.positive_admission?.explanation).toContain("Only this Alpha's pool is affected");
    // the text rule is the unchanged baseline, not a rewritten one
    expect(c?.text_rule?.relation).toBe("activation");
    const item = (adaptEvidenceTraceItemResponse(excluded) as { ok: true; value: { item: { scoring: { not_scored_code: string | null } } } }).value.item;
    expect(item.scoring.not_scored_code).toBe("STANCE_MODEL_NOT_SUPPORTING");
  });

  it("copies the unjudged disclosure and never turns it into an exclusion", () => {
    const c = consumptionOf(unjudged);
    expect(c?.stance?.state).toBe("UNJUDGED");
    expect(c?.stance?.unjudged_category).not.toBeNull();
    expect(c?.stance?.unjudged_reason).not.toBeNull();
    expect(c?.positive_admission).toMatchObject({ admitted: true, reason_code: null });
  });

  it("copies a model weight and level when a later contract version supplies one (today none exists, so none is shown)", () => {
    const base = JSON.parse(JSON.stringify(admitted));
    expect(consumptionOf(base)?.relevance).toMatchObject({ model_weight: null, model_level: null });
    base.item.consumption.relevance.model_weight = 0.42;
    base.item.consumption.relevance.model_level = "core";
    base.item.consumption.relevance.weight_authority = "MODEL";
    expect(consumptionOf(base)?.relevance).toMatchObject({ model_weight: 0.42, model_level: "core", weight_authority: "MODEL" });
  });

  it("is null for a run that never declared the contract", () => {
    expect(consumptionOf(legacyClaim)).toBeNull();
  });

  it("keeps a stale or invalid state instead of normalising it away", () => {
    const base = JSON.parse(JSON.stringify(admitted));
    base.item.consumption.state = "STALE";
    expect(consumptionOf(base)?.state).toBe("STALE");
    base.item.consumption.state = "INVALID:EVIDENCE_CONSUMPTION_BINDING_STALE";
    base.item.consumption.verification_error = "EVIDENCE_CONSUMPTION_BINDING_STALE";
    const c = consumptionOf(base);
    expect(c?.state).toBe("INVALID:EVIDENCE_CONSUMPTION_BINDING_STALE");
    expect(c?.verification_error).toBe("EVIDENCE_CONSUMPTION_BINDING_STALE");
  });

  it("reads the attribution-only shape of a claim matched to no Alpha (no stance, no admission, no weight)", () => {
    const base = JSON.parse(JSON.stringify(admitted));
    base.item.consumption = {
      contract: "alpha_evidence_consumption.v2",
      state: "NOT_APPLICABLE",
      verification_error: null,
      scope: "attribution_only (the claim is matched to no Alpha)",
      attribution: { category: "TARGET_NAME_ISSUER", ticker_specific: true, subject_determined: false, limits: ["NAME_PRESENCE_NOT_SUBJECT"], basis: [{ kind: "issuer_name", term: "NVIDIA" }], other_issuers_named: [] },
    };
    const c = consumptionOf(base);
    expect(c).toMatchObject({ state: "NOT_APPLICABLE", alpha_id: null, stance: null, positive_admission: null, relevance: null, binding: null, text_rule: null });
    expect(c?.attribution).toMatchObject({ ticker_specific: true, subject_determined: false, limits: ["NAME_PRESENCE_NOT_SUBJECT"], basis: [{ kind: "issuer_name", term: "NVIDIA" }] });
  });

  it("ignores unknown extra fields and rejects a block without a contract", () => {
    const base = JSON.parse(JSON.stringify(admitted));
    base.item.consumption.surprise = { anything: 1 };
    base.item.consumption.stance.surprise = "x";
    expect(consumptionOf(base)).not.toBeNull();
    base.item.consumption = { state: "CURRENT" };
    expect(consumptionOf(base)).toBeNull();
    base.item.consumption = "alpha_evidence_consumption.v2";
    expect(consumptionOf(base)).toBeNull();
  });

  it("reads a missing admission flag as 'not excluded' only when it is absent, never when it is explicitly false", () => {
    const base = JSON.parse(JSON.stringify(excluded));
    expect(consumptionOf(base)?.positive_admission?.admitted).toBe(false);
    base.item.consumption.positive_admission.admitted = true;
    expect(consumptionOf(base)?.positive_admission?.admitted).toBe(true);
  });
});

describe("trace adapter: negation scope (alpha_statement_scope.v2)", () => {
  // REAL backend output: GET /api/research/<execution>/evidence-trace on the independent viewer (8031) -- NVDA v2
  // consumption-20261013T194357Z-93df2796 (re-read, governs) and AMD v2 consumption-20261013T194415Z-2fb3a562 (unanchored)
  it("copies a re-read: the rejected alternative removed, the effective reading, and the stance read on that basis", () => {
    const adapted = adaptEvidenceTraceItemResponse(negationReread);
    if (!adapted.ok) throw new Error(adapted.reason);
    const { item } = adapted.value;
    expect(item.consumption?.statement_scope).toMatchObject({
      policy: "alpha_statement_scope.v2",
      applies: true,
      governing_negation: false,
      changed: true,
      removed: [{ basis: "CONTRAST_ALTERNATIVE", text: "They're not —" }],
      not_applied: [],
      anchor: "MODEL_JUDGED_SUPPORTS_ALPHA",
      remaining_negators: [],
      effective: { relation: "activation", assertion_status: "asserted" },
    });
    expect(item.consumption?.statement_scope?.explanation).toMatch(/it does not negate A304's statement/);
    expect(item.stance).toMatchObject({ status_code: "MODEL_JUDGED", relation: "activation", assertion_status: "asserted" });
    expect(item.stance.relation_basis).toMatch(/alpha_statement_scope\.v2/);
  });

  it("copies a governing negation and leaves the text rule's reading in force", () => {
    const adapted = adaptEvidenceTraceItemResponse(negationGoverns);
    if (!adapted.ok) throw new Error(adapted.reason);
    const { item } = adapted.value;
    expect(item.consumption?.statement_scope).toMatchObject({
      applies: true,
      governing_negation: true,
      changed: false,
      removed: [],
      not_applied: [],
      remaining_negators: ["not"],
      effective: { relation: "mention", assertion_status: "negated" },
    });
    expect(item.stance).toMatchObject({ status_code: "RELATION_UNRESOLVED", relation: "mention", relation_basis: "text rule (claim_semantics)" });
  });

  it("copies a contrast left in place for want of an anchor (no ledger: no model judgment that the claim supports the Alpha)", () => {
    const adapted = adaptEvidenceTraceItemResponse(negationUnanchored);
    if (!adapted.ok) throw new Error(adapted.reason);
    const { item } = adapted.value;
    expect(item.consumption?.statement_scope).toMatchObject({
      applies: true,
      governing_negation: true,
      changed: false,
      anchor: null,
      not_applied: [{ basis: "CONTRAST_ALTERNATIVE", text: ", not a forward EPS of $15.72   against a current quarterly run-rate of $1.38" }],
      effective: { relation: "mention", assertion_status: "negated" },
    });
    expect(item.consumption?.statement_scope?.removed.map((entry) => entry.basis)).toEqual(["CITATION_MARKER", "CITATION_MARKER"]);
    expect(item.consumption?.statement_scope?.explanation).toMatch(/the words alone cannot tell whether A304's statement is the kept or the rejected part/);
    expect(item.stance.status_code).toBe("RELATION_UNRESOLVED");
  });

  it("has no negation scope for a run that never declared the contract", () => {
    const adapted = adaptEvidenceTraceItemResponse(legacyClaim);
    if (!adapted.ok) throw new Error(adapted.reason);
    expect(adapted.value.item.consumption?.statement_scope ?? null).toBeNull();
  });
});

describe("key-conclusions adapter: run-level execution basis", () => {
  const SOURCE = "12591384-0b26-470d-a99d-a49c00be440b";
  const EXEC = "consumption-20261012T000034Z-673b19aa";
  // the execution_basis object exactly as the production route builds it for a consumption recompute execution
  const basis = {
    execution_run_id: EXEC,
    execution_type: "alpha_evidence_consumption_recompute",
    based_on_run_id: SOURCE,
    root_research_run_id: null,
    recomputation_of_saved_inputs: true,
    label:
      "Recomputation of a saved run's inputs under the evidence contract -- not a Fresh Run. This execution made no model, search or data-fetch call; every stance is the source run's saved result (nothing was re-judged).",
    stance_ledger: { available: true, integrity: "MATCHES_MANIFEST", sha256: "6076153fdde048e5", owner_run_id: SOURCE, binding: "SOURCE_RUN_DECLARED", usable: true },
  };
  const response = (extra: Record<string, unknown>) => ({
    run_id: EXEC,
    ticker: "NVDA",
    status: "ok",
    key_conclusions: { rule: "final-decision chain", claim_count: 0, status_counts: {}, groups: [], agent_wording_verified_count: 0, ...extra },
  });

  it("copies the execution basis of a recomputation of saved inputs", () => {
    const adapted = adaptKeyConclusionsResponse(response({ execution_basis: basis }));
    if (!adapted.ok) throw new Error(adapted.reason);
    expect(adapted.value.key_conclusions.execution_basis).toMatchObject({
      execution_run_id: EXEC,
      based_on_run_id: SOURCE,
      recomputation_of_saved_inputs: true,
      label: basis.label,
      stance_ledger: { owner_run_id: SOURCE, binding: "SOURCE_RUN_DECLARED" },
    });
  });

  it("is null when the payload carries none (every run outside the contract and the recompute entry)", () => {
    const adapted = adaptKeyConclusionsResponse(response({}));
    if (!adapted.ok) throw new Error(adapted.reason);
    expect(adapted.value.key_conclusions.execution_basis).toBeNull();
  });
});
