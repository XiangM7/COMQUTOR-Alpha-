"""T3 corrected re-score (2026-10-06), per direct user instruction: the
frozen prediction file t3_eval_records.jsonl (execution
t3live_20261001T014648Z_1fb9c9d5, 2026-10-01) carries a stale outcome_code
for 5/40 records -- classify_outcome's OWN docstring (2026-10-01, AI-review
comparison round) documents that these 5 were generated by an EARLIER,
buggy version of this function that mapped (llm_selected, no_match) to
"MATCHED" with predicted_alpha=None, instead of the current, correct
"SELECTED_BUT_NOT_MATCHED". The docstring explicitly states this was never
retroactively applied to that execution's own saved file.

This script never modifies t3_eval_records.jsonl or the original score
result. It recomputes outcome_code for all 40 records from their own
already-saved classifier_status_raw/match_status_raw (zero new Provider
calls -- these are real, already-recorded classifier outputs), using the
driver's own current classify_outcome function, then re-runs the SAME,
unmodified score_against_human_labels on the corrected records.

Also reports, separately and explicitly (never conflated):
  1. "raw model selection" -- classifier_status_raw distribution alone
     (did the LLM itself pick a real Alpha ID or say none, before ANY
     post-hoc gate).
  2. "product-gate-filtered result" -- the corrected outcome_code
     distribution (after alpha_mapper.py's own real semantic gates).
  3. Old (stale) vs corrected scoring, side by side, to show precisely
     what changed and why.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, ".")
sys.path.insert(0, "docs/audit_artifacts/round_source_linking_t0_t2")

from t3_diagnostic_evaluation_driver import classify_outcome, score_against_human_labels

PREDICTION_DIR = Path("outputs/t3_evaluations/t3live_20261001T014648Z_1fb9c9d5")
REVIEW_FORM_PATH = Path("docs/audit_artifacts/round_source_linking_t0_t2/t3_human_review_form_2026-09-30.json")

raw_records = [json.loads(line) for line in (PREDICTION_DIR / "t3_eval_records.jsonl").read_text().splitlines()]
review_doc = json.loads(REVIEW_FORM_PATH.read_text())
review_items = review_doc["review_items"]

# --- 1. Raw model selection distribution (classifier_status_raw alone, before ANY gate) ---
raw_selection_counts: dict[str, int] = {}
for r in raw_records:
    status = r.get("classifier_status_raw")
    raw_selection_counts[status] = raw_selection_counts.get(status, 0) + 1

# --- 2. Recompute outcome_code for every record from its own saved raw fields ---
corrected_records = []
changed = []
for r in raw_records:
    corrected = dict(r)
    new_outcome = classify_outcome(r.get("classifier_status_raw"), r.get("match_status_raw"))
    old_outcome = r.get("outcome_code")
    corrected["outcome_code"] = new_outcome
    if new_outcome != old_outcome:
        changed.append({
            "sample_id": r["sample_id"],
            "classifier_status_raw": r.get("classifier_status_raw"),
            "match_status_raw": r.get("match_status_raw"),
            "old_outcome_code": old_outcome,
            "corrected_outcome_code": new_outcome,
            "predicted_alpha": r.get("predicted_alpha"),
        })
    corrected_records.append(corrected)

corrected_outcome_counts: dict[str, int] = {}
for r in corrected_records:
    corrected_outcome_counts[r["outcome_code"]] = corrected_outcome_counts.get(r["outcome_code"], 0) + 1

# --- 3. Score BOTH the stale (original) and corrected records, side by side ---
stale_scoring = score_against_human_labels(raw_records, review_items)
corrected_scoring = score_against_human_labels(corrected_records, review_items)

output = {
    "source_prediction_execution_id": "t3live_20261001T014648Z_1fb9c9d5",
    "source_predictions_file": str(PREDICTION_DIR / "t3_eval_records.jsonl"),
    "original_file_modified": False,
    "raw_model_selection_distribution_BEFORE_ANY_GATE": raw_selection_counts,
    "corrected_product_gate_outcome_distribution": corrected_outcome_counts,
    "records_with_a_stale_outcome_code": changed,
    "stale_outcome_code_count": len(changed),
    "scoring_WITH_STALE_OUTCOME_CODE_as_originally_scored_20261005": stale_scoring,
    "scoring_WITH_CORRECTED_OUTCOME_CODE": corrected_scoring,
}
print(json.dumps(output, indent=2, default=str))
