"""2026-10-06 (round 14, section 8): zero-model-call proof for the
post-recovery recompute path.

After a real alpha_classifier recovery, Evidence Fact / Activation /
Exposure / Conflict are regenerated by the existing production function
routes_research._run_week3_graph_pipeline -- which takes no gateway at all.
This test proves that empirically, not just by reading the signature: every
model/network seam is trapped, the real pipeline is run against a scratch
copy of the frozen c904d4cc inputs, and the trap must never fire.

The 'recovered-shape' variant rewrites provider_error entries into valid
NONE entries in a SCRATCH COPY ONLY. That is a synthetic stand-in used
purely to exercise the downstream path's call behavior; it never touches
outputs/runs/ and is never presented as a real classification result.
"""

from __future__ import annotations

import json
import shutil
import socket
from pathlib import Path

import httpx
import pytest

from comqutor_alpha.api import routes_research
from comqutor_alpha.storage.db.engine import build_engine
from comqutor_alpha.storage.db.migrations import apply_migrations
from comqutor_alpha.storage.db.repository import GraphPersistenceRepository
from comqutor_alpha.structure_engine.week2_llm import Week2LLMGateway

REPO_ROOT = Path(__file__).resolve().parents[1]
RUN_ID = "c904d4cc-dc09-495c-aec5-b056979948e1"
FROZEN_DIR = REPO_ROOT / "outputs" / "runs" / RUN_ID
INPUT_FILES = (
    "alpha_matches.json",
    "extracted_structures.json",
    "structured_agent_outputs.json",
    "source_registry.json",
    "metadata.json",
)

pytestmark = pytest.mark.skipif(
    not all((FROZEN_DIR / name).exists() for name in INPUT_FILES),
    reason="frozen c904d4cc inputs not present",
)


@pytest.fixture
def model_call_trap(monkeypatch):
    hits: list[str] = []

    def _trap(name):
        def _raise(*args, **kwargs):
            hits.append(name)
            raise AssertionError(f"model/network seam reached during downstream recompute: {name}")
        return _raise

    monkeypatch.setattr(httpx.HTTPTransport, "handle_request", _trap("httpx.HTTPTransport.handle_request"))
    monkeypatch.setattr(httpx.Client, "send", _trap("httpx.Client.send"))
    monkeypatch.setattr(socket.socket, "connect", _trap("socket.connect"))
    for method in ("invoke_json", "invoke_json_with_trace", "invoke_prebuilt_json_prompt"):
        monkeypatch.setattr(Week2LLMGateway, method, _trap(f"Week2LLMGateway.{method}"))
    import tradingagents.llm_clients as llm_clients
    monkeypatch.setattr(llm_clients, "create_llm_client", _trap("create_llm_client"))
    return hits


def _scratch_run(tmp_path: Path, *, rewrite_failures_as_valid_none: bool) -> Path:
    run_dir = tmp_path / RUN_ID
    run_dir.mkdir()
    for name in INPUT_FILES:
        shutil.copy2(FROZEN_DIR / name, run_dir / name)
    if rewrite_failures_as_valid_none:
        payload = json.loads((run_dir / "alpha_matches.json").read_text())
        for match in payload["matches"]:
            if match.get("alpha_match_method") == "llm_unavailable":
                match["alpha_match_method"] = "llm"
                match["alpha_match_fallback_reason"] = None
        (run_dir / "alpha_matches.json").write_text(json.dumps(payload))
    return run_dir


def _repo():
    engine = build_engine("sqlite:///:memory:")
    apply_migrations(engine)
    return GraphPersistenceRepository(engine)


@pytest.mark.parametrize("rewrite", [False, True], ids=["as_frozen", "recovered_shape_synthetic"])
def test_downstream_recompute_makes_zero_model_or_network_calls(tmp_path, model_call_trap, rewrite):
    run_dir = _scratch_run(tmp_path, rewrite_failures_as_valid_none=rewrite)
    repo = _repo()

    routes_research._run_week3_graph_pipeline(run_dir, graph_repository=repo)

    assert model_call_trap == [], f"downstream recompute reached a model/network seam: {model_call_trap}"
    status = json.loads((run_dir / "week3_pipeline_status.json").read_text())
    assert status.get("outcome") == "success", status
    assert (run_dir / "structure_graph.json").exists()
    assert (run_dir / "alpha_activations.json").exists()


def test_completion_status_flips_only_when_failures_are_actually_resolved(tmp_path, model_call_trap):
    """Same downstream path, same frozen inputs: as-frozen (973 real
    failures) must read 'incomplete'; only after the failures are resolved
    (synthetic stand-in here) may it read a complete state."""
    statuses = {}
    for label, rewrite in (("as_frozen", False), ("recovered_shape", True)):
        scratch = tmp_path / label
        scratch.mkdir()
        run_dir = _scratch_run(scratch, rewrite_failures_as_valid_none=rewrite)
        repo = _repo()
        routes_research._run_week3_graph_pipeline(run_dir, graph_repository=repo)
        response = routes_research.build_research_response(
            RUN_ID, output_root=str(scratch), graph_repository=repo
        )
        statuses[label] = response["alpha_classification_status"]

    assert model_call_trap == []
    assert statuses["as_frozen"] == "incomplete"
    assert statuses["recovered_shape"] in {"complete_no_active", "complete_active_no_dominant", "complete_has_dominant"}
